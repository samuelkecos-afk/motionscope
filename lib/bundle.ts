// Packs a scan into one ZIP a builder can use without the extension.

import { strToU8, zipSync } from 'fflate';
import { buildBrief } from './brief';
import { motionToCss, motionToGsap, toCssVariables, toDTCG, toTailwindTheme, trackToGsap } from './export';
import type { FullScan, ScrollRecording } from './types';

export function hostOf(url: string) {
  try {
    return new URL(url).hostname.replace(/^www\./, '');
  } catch {
    return 'page';
  }
}

export function gsapCode(data: FullScan, recording?: ScrollRecording) {
  const parts = data.motions.filter((m) => m.engine === 'gsap' && m.target !== '(timeline)' && m.target !== '(none)').map(motionToGsap);
  if (recording) parts.push(...recording.tracks.map(trackToGsap));
  if (!parts.length) return '// No GSAP motion found. Record a scroll to generate ScrollTrigger code.\n';
  return [
    `// GSAP recreation of the motion on ${data.url}`,
    '// Generated by MotionScope. Requires gsap and gsap/ScrollTrigger.',
    "import { gsap } from 'gsap';",
    "import { ScrollTrigger } from 'gsap/ScrollTrigger';",
    'gsap.registerPlugin(ScrollTrigger);',
    '',
    "const mm = gsap.matchMedia();",
    "mm.add('(prefers-reduced-motion: no-preference)', () => {",
    ...parts.join('\n\n').split('\n').map((l) => (l ? `  ${l}` : l)),
    '});',
    '',
  ].join('\n');
}

export function cssAnimations(data: FullScan) {
  const items = data.motions.filter((m) => (m.engine === 'css-animation' || m.engine === 'waapi') && m.keyframes.length >= 2);
  if (!items.length) return '/* No CSS or Web Animations found. */\n';
  return `/* CSS recreation of the keyframe animations on ${data.url} (generated by MotionScope) */\n\n` +
    `@media (prefers-reduced-motion: no-preference) {\n\n${items.map(motionToCss).join('\n\n')}\n\n}\n`;
}

export function buildBundle(data: FullScan, recording?: ScrollRecording): { name: string; zip: Uint8Array; brief: string } {
  const host = hostOf(data.url);
  const dir = `motionscope-${host}`;
  const brief = buildBrief(data, recording);
  const json = (v: unknown) => strToU8(JSON.stringify(v, null, 2));
  const files: Record<string, Uint8Array> = {
    [`${dir}/README.md`]: strToU8(brief),
    [`${dir}/tokens/tokens.dtcg.json`]: json(toDTCG(data.tokens)),
    [`${dir}/tokens/tokens.css`]: strToU8(toCssVariables(data.tokens) + '\n'),
    [`${dir}/tokens/tailwind-theme.css`]: strToU8(`@import "tailwindcss";\n\n${toTailwindTheme(data.tokens)}\n`),
    [`${dir}/motion/motion.json`]: json({
      source: data.url,
      capturedAt: data.scannedAt,
      libraries: data.libraries,
      animations: data.motions,
      scrollRecording: recording ?? null,
      splitText: data.splitText,
    }),
    [`${dir}/motion/animations.css`]: strToU8(cssAnimations(data)),
    [`${dir}/motion/site-keyframes.css`]: strToU8(
      data.stylesheetKeyframes.map((k) => (k.aliases?.length ? `/* Same as: ${k.aliases.join(', ')} */\n` : '') + k.css).join('\n\n') + '\n',
    ),
    [`${dir}/motion/gsap-animations.js`]: strToU8(gsapCode(data, recording)),
    [`${dir}/raw/scan.json`]: json({ ...data, scrollRecording: recording ?? null }),
  };
  return { name: `${dir}.zip`, zip: zipSync(files, { level: 6 }), brief };
}
